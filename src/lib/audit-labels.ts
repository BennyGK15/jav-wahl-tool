const PREFIX: Record<string, string> = {
  "nomination.candidate": "Bewerber/in geändert",
  "nomination.supporter": "Stützunterschrift geändert",
  "assembly.candidate": "Bewerber/in Wahlversammlung geändert",
  briefwahl: "Briefwahl-Schritt geändert",
};

export function auditLabel(action: string): string {
  if (LABELS[action]) return LABELS[action];
  const p = Object.keys(PREFIX).find((k) => action.startsWith(k));
  return p ? PREFIX[p]! : action;
}

